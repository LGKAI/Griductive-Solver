"""Generate the data-driven parts of the LaTeX report.

Everything numeric in the report comes from here, so the text can never drift
from the code or the experiment results:

* generated/cnf_examples.tex - clauses produced by the real ClueEncoder
* generated/results.tex      - experiment tables (from Source/results/experiments.json)
* generated/charts.tex       - pgfplots charts from the same data
* generated/macros.tex       - summary numbers used in the prose

Run from Lab2/:  python3 report_latex/gen_data.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "Source"
OUT = HERE / "generated"
sys.path.insert(0, str(SRC))

from griductive.board import Board  # noqa: E402
from griductive.clues import parse_clue  # noqa: E402
from griductive.cnf import CNF, ClueEncoder, VarMap  # noqa: E402
from griductive.themes import THEMES  # noqa: E402

CONFIGS = ("filter+auto", "naive+auto", "filter+counter")


# ------------------------------------------------------------ CNF examples
def lit_tex(varmap: VarMap, lit: int) -> str:
    v = abs(lit)
    name = f"C_{{\\mathrm{{{varmap.cell(v)}}}}}" if varmap.is_primary(v) else f"y_{{{v}}}"
    return name if lit > 0 else f"\\neg {name}"


def encode(size: int, clue: dict, mode: str = "auto") -> tuple[list[list[int]], VarMap, int]:
    board = Board(size)
    varmap = VarMap(board)
    cnf = CNF(varmap.num_primary)
    ClueEncoder(varmap, mode).encode(cnf, parse_clue(board, clue, "X"))
    return cnf.clauses, varmap, cnf.num_aux


def clauses_tex(size: int, clue: dict, mode: str = "auto", per_line: int = 3, limit: int = 24) -> tuple[str, int, int]:
    clauses, varmap, aux = encode(size, clue, mode)
    parts = ["(" + " \\lor ".join(lit_tex(varmap, l) for l in c) + ")" if c else "\\square" for c in clauses[:limit]]
    lines = [" \\land ".join(parts[i:i + per_line]) for i in range(0, len(parts), per_line)]
    body = " \\land \\\\\n& ".join(lines)
    if len(clauses) > limit:
        body += f" \\land \\dots \\text{{ ({len(clauses) - limit} mệnh đề nữa)}}"
    return f"\\begin{{align*}}\n& {body}\n\\end{{align*}}", len(clauses), aux


EXAMPLES = {
    "Same": (3, {"type": "SAME", "a": "A1", "b": "C3"}, "auto"),
    "Diff": (3, {"type": "DIFFERENT", "a": "A1", "b": "B1"}, "auto"),
    "Implies": (3, {"type": "IMPLIES", "if": {"cell": "A1", "status": "criminal"},
                    "then": {"cell": "B2", "status": "innocent"}}, "auto"),
    "Exactly": (3, {"type": "EXACTLY", "k": 2, "region": {"kind": "neighbors", "of": "A1"}}, "auto"),
    "ExactlyInn": (3, {"type": "EXACTLY", "k": 1, "region": {"kind": "row", "index": 2}, "who": "innocent"}, "auto"),
    "AtMostCounter": (3, {"type": "AT_MOST", "k": 1, "region": {"kind": "cells", "cells": ["A1", "B1", "C1"]}}, "counter"),
    "AtMostDirect": (3, {"type": "AT_MOST", "k": 1, "region": {"kind": "cells", "cells": ["A1", "B1", "C1"]}}, "direct"),
    "Parity": (3, {"type": "PARITY", "parity": "odd", "region": {"kind": "cells", "cells": ["A1", "B1", "C1"]}}, "auto"),
    "Connected": (4, {"type": "CONNECTED", "region": {"kind": "row", "index": 1}}, "auto"),
    "Compare": (3, {"type": "COMPARE", "op": "more", "left": {"kind": "cells", "cells": ["A1", "B1"]},
                    "right": {"kind": "cells", "cells": ["C3"]}}, "auto"),
}


def cnf_examples() -> str:
    out = ["% generated by gen_data.py - do not edit"]
    for key, (size, clue, mode) in EXAMPLES.items():
        tex, n, aux = clauses_tex(size, clue, mode)
        out.append(f"\\newcommand{{\\Ex{key}}}{{{tex}}}")
        out.append(f"\\newcommand{{\\Ex{key}N}}{{{n}}}")
        out.append(f"\\newcommand{{\\Ex{key}Aux}}{{{aux}}}")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- results
def load_rows() -> tuple[dict, list[dict]]:
    data = json.loads((SRC / "results" / "experiments.json").read_text(encoding="utf-8"))
    rows = data["rows"]
    found = {r["config"] for r in rows}
    missing = set(CONFIGS) - found
    if missing:
        raise SystemExit(f"experiments.json lacks {sorted(missing)}: run the full `python3 experiments.py` first")
    return data, rows


def by(rows, config):
    return [r for r in rows if r["config"] == config]


def fmt(x) -> str:
    if isinstance(x, float):
        return f"{x:.1f}"
    return f"{x:,}".replace(",", "\\,") if isinstance(x, int) else str(x)


def outcome(o: str) -> str:
    colour = {"SOLVED": "solved", "STUCK": "stuck", "INCONSISTENT": "incons"}.get(o, "stuck")
    return f"\\textcolor{{{colour}}}{{\\textbf{{\\scriptsize {o}}}}}"


def short(puzzle: str) -> str:
    return puzzle.replace("-ambiguous", "-amb").replace("-inconsistent", "-inc")


def results_tex(rows) -> str:
    main = by(rows, "filter+auto")
    lines = ["% generated by gen_data.py - do not edit",
             "\\begin{table}[!htbp]\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}",
             "\\resizebox{\\textwidth}{!}{%",
             "\\begin{tabular}{lcrrrrrrrrrrl}\\toprule",
             "Puzzle & Kết quả & Biến chính & Biến phụ & Mệnh đề & SAT & Quyết định & Lan truyền & Quay lui & Bước & Wave & ms & Duy nhất\\\\\\midrule"]
    for r in main:
        lines.append(" & ".join([
            f"\\texttt{{{short(r['puzzle'])}}}", outcome(r["outcome"]), fmt(r["primary_vars"]), fmt(r["aux_vars"]),
            fmt(r["clauses"]), fmt(r["sat_calls"]), fmt(r["decisions"]), fmt(r["propagations"]), fmt(r["backtracks"]),
            fmt(r["steps"]), fmt(r["waves"]), fmt(r["runtime_ms"]), "\\scriptsize " + r["uniqueness"].replace("_", r"\_")]) + "\\\\")
    lines += ["\\bottomrule\\end{tabular}}",
              "\\caption{Kết quả với cấu hình mặc định (\\texttt{filter} + \\texttt{auto}). ``Biến chính/phụ'' và ``Mệnh đề'' là kích thước "
              "$\\KB_t$ lớn nhất trong lượt giải; ``SAT'' là tổng số lần gọi DPLL của agent; ``ms'' là thời gian thực của cả vòng suy diễn "
              "(gồm cả việc engine kiểm tra lại từng phán đoán).}",
              "\\label{tab:main}\\end{table}", ""]

    naive, counter = {r["puzzle"]: r for r in by(rows, "naive+auto")}, {r["puzzle"]: r for r in by(rows, "filter+counter")}
    lines += ["\\begin{table}[!htbp]\\centering\\scriptsize\\setlength{\\tabcolsep}{3.5pt}",
              "\\resizebox{\\textwidth}{!}{%",
              "\\begin{tabular}{l rr rr | rr rr rr}\\toprule",
              " & \\multicolumn{2}{c}{Số lần gọi SAT} & \\multicolumn{2}{c|}{Thời gian (ms)} & "
              "\\multicolumn{2}{c}{Biến phụ} & \\multicolumn{2}{c}{Mệnh đề} & \\multicolumn{2}{c}{Lan truyền}\\\\",
              "Puzzle & naive & filter & naive & filter & auto & counter & auto & counter & auto & counter\\\\\\midrule"]
    for r in main:
        n, c = naive[r["puzzle"]], counter[r["puzzle"]]
        lines.append(" & ".join([f"\\texttt{{{short(r['puzzle'])}}}", fmt(n["sat_calls"]), fmt(r["sat_calls"]),
                                 fmt(n["runtime_ms"]), fmt(r["runtime_ms"]), fmt(r["aux_vars"]), fmt(c["aux_vars"]),
                                 fmt(r["clauses"]), fmt(c["clauses"]), fmt(r["propagations"]), fmt(c["propagations"])]) + "\\\\")
    lines += ["\\bottomrule\\end{tabular}}",
              "\\caption{So sánh chiến lược truy vấn (\\texttt{naive} và \\texttt{filter}, cùng mã hóa \\texttt{auto}) "
              "và cách mã hóa ràng buộc đếm (\\texttt{auto} và \\texttt{counter}, cùng chiến lược \\texttt{filter}).}",
              "\\label{tab:compare}\\end{table}", ""]
    return "\n".join(lines)


def charts_tex(rows) -> str:
    puzzles = [r["puzzle"] for r in by(rows, "filter+auto")]
    labels = [p.split("-")[0] for p in puzzles]
    coords = ",".join(labels)

    def series(config, key):
        data = {r["puzzle"]: r[key] for r in by(rows, config)}
        return " ".join(f"({lab},{max(data[p], 0.01) if key == 'runtime_ms' else data[p]})" for lab, p in zip(labels, puzzles))

    def chart(title, ylabel, plots, log=False):
        axis = "semilogyaxis" if log else "axis"
        extra = "log origin=infty," if log else ""
        legend = ",".join(name for name, _, _ in plots)
        body = "\n".join(f"\\addplot[fill={colour},draw=none] coordinates {{{coords_}}};" for _, colour, coords_ in plots)
        return (f"\\begin{{tikzpicture}}\\begin{{{axis}}}[{extra}width=0.94\\linewidth,height=5.2cm,ybar,/pgf/number format/1000 sep={{\\,}},bar width=4pt,"
                f"symbolic x coords={{{coords}}},xtick=data,ymin={0.01 if log else 0},ylabel={{{ylabel}}},"
                f"title={{\\small {title}}},legend style={{at={{(0.02,0.98)}},anchor=north west,font=\\scriptsize,draw=none,fill=white,fill opacity=.8,text opacity=1}},"
                f"tick label style={{font=\\scriptsize}},label style={{font=\\footnotesize}},enlarge x limits=0.05,ymajorgrids,grid style={{gray!25}}]\n"
                f"{body}\n\\legend{{{legend}}}\n\\end{{{axis}}}\\end{{tikzpicture}}")

    sat = chart("Số lần gọi SAT của agent theo chiến lược", "Số lần gọi SAT",
                [("naive", "naivec", series("naive+auto", "sat_calls")),
                 ("filter", "filterc", series("filter+auto", "sat_calls"))])
    clauses = chart("Số mệnh đề của $\\KB_t$ lớn nhất theo cách mã hóa", "mệnh đề",
                    [("auto (trực tiếp khi nhỏ)", "filterc", series("filter+auto", "clauses")),
                     ("counter", "counterc", series("filter+counter", "clauses"))])
    runtime = chart("Tổng thời gian giải (thang log)", "ms",
                    [("filter+auto", "filterc", series("filter+auto", "runtime_ms")),
                     ("naive+auto", "naivec", series("naive+auto", "runtime_ms")),
                     ("filter+counter", "counterc", series("filter+counter", "runtime_ms"))], log=True)
    return "% generated by gen_data.py - do not edit\n" + "\n".join(
        f"\\newcommand{{\\Chart{name}}}{{{tex}}}" for name, tex in (("Sat", sat), ("Clauses", clauses), ("Runtime", runtime))) + "\n"


def macros_tex(data, rows) -> str:
    solved = [r for r in rows if r["expected"] == "SOLVED"]
    f_sat = sum(r["sat_calls"] for r in solved if r["config"] == "filter+auto")
    n_sat = sum(r["sat_calls"] for r in solved if r["config"] == "naive+auto")
    unexpected = sum(1 for r in rows if r["outcome"] != r["expected"])
    ratios = []
    for r in (x for x in by(rows, "filter+auto") if x["expected"] == "SOLVED"):
        c = next(x for x in by(rows, "filter+counter") if x["puzzle"] == r["puzzle"])
        ratios.append(c["clauses"] / r["clauses"])
    slowest = max(by(rows, "filter+auto"), key=lambda r: r["runtime_ms"])
    tests = sum(len(re.findall(r"^\s+def test_", p.read_text(encoding="utf-8"), re.M))
                for p in (SRC / "tests").glob("test_*.py"))
    m = {
        "NumRuns": len(rows), "NumPuzzles": len(by(rows, "filter+auto")), "Unexpected": unexpected,
        "FilterSat": f"{f_sat:,}".replace(",", "\\,"), "NaiveSat": f"{n_sat:,}".replace(",", "\\,"),
        "SatSaving": f"{100 * (1 - f_sat / n_sat):.1f}",
        "CounterMin": f"{min(ratios):.1f}", "CounterMax": f"{max(ratios):.1f}",
        "SlowPuzzle": slowest["puzzle"], "SlowMs": f"{slowest['runtime_ms']:.1f}",
        "PyVersion": data["python"], "NumTests": tests,
        "AgentSatShare": f"{100 * sum(r['agent_sat_ms'] for r in by(rows, 'filter+auto')) / sum(r['runtime_ms'] for r in by(rows, 'filter+auto')):.0f}",
        "MaxBacktracks": max(r["backtracks"] for r in by(rows, "filter+auto")),
        "CastFootball": len(THEMES["football"].cast),
    }
    return "% generated by gen_data.py - do not edit\n" + "\n".join(
        f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()) + "\n"


def trace_tex(puzzle: str = "01-3x3-a", lines: int = 22) -> str:
    """First lines of the real CLI trace (`main.py --solve ... -v`)."""
    import subprocess
    out = subprocess.run([sys.executable, "main.py", "--solve", f"puzzles/{puzzle}.json", "-v"], cwd=SRC,
                         capture_output=True, text=True, check=False).stdout.splitlines()[:lines]
    body = "\n".join(out).replace("\\", "/").replace("{", "(").replace("}", ")").replace("∧", "\\ensuremath{\\land}")
    return ("% generated by gen_data.py - do not edit\n"
            "\\begin{Verbatim}[commandchars=\\\\\\{\\}, fontsize=\\scriptsize]\n" + body + "\n\\end{Verbatim}\n")


def main() -> None:
    OUT.mkdir(exist_ok=True)
    data, rows = load_rows()
    (OUT / "cnf_examples.tex").write_text(cnf_examples(), encoding="utf-8")
    (OUT / "results.tex").write_text(results_tex(rows), encoding="utf-8")
    (OUT / "charts.tex").write_text(charts_tex(rows), encoding="utf-8")
    (OUT / "macros.tex").write_text(macros_tex(data, rows), encoding="utf-8")
    (OUT / "trace.tex").write_text(trace_tex(), encoding="utf-8")
    print(f"wrote {', '.join(sorted(p.name for p in OUT.glob('*.tex')))}")


if __name__ == "__main__":
    main()
